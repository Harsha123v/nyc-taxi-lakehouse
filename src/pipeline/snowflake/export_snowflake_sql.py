"""Generate the Snowflake SQL that exposes the Iceberg tables.

Writes:
  snowflake/generated/01_setup.sql   - warehouse, DB, external volume, catalog integration
  snowflake/generated/02_tables.sql  - CREATE ICEBERG TABLE ... + REFRESH to the
                                       CURRENT metadata.json of each table

The current metadata file is read from Iceberg's `metadata_log_entries`
metadata table via Spark/Polaris; its path is made relative to the external
volume's base URL (s3://<bucket>/warehouse/).

Re-run after every pipeline run, then execute 02_tables.sql, so Snowflake
sees the latest snapshot.

Run: python -m pipeline.snowflake.export_snowflake_sql
"""
from __future__ import annotations

from pipeline.config import REPO_ROOT, load_config, require
from pipeline.spark_session import build_spark

SNOWFLAKE_DIR = REPO_ROOT / "snowflake"
TABLES = ("trips_clean", "daily_zone_metrics", "trips_rejected")


def render_setup(bucket: str, account_id: str) -> str:
    tpl = (SNOWFLAKE_DIR / "01_setup.sql.tpl").read_text()
    return tpl.replace("${BUCKET}", bucket).replace("${AWS_ACCOUNT_ID}", account_id)


def relative_metadata_path(metadata_file: str, warehouse_url: str) -> str:
    """s3://b/warehouse/ns/t/metadata/x.json -> ns/t/metadata/x.json"""
    for scheme in ("s3://", "s3a://"):
        prefix = warehouse_url.replace("s3://", scheme)
        if metadata_file.startswith(prefix):
            return metadata_file[len(prefix):]
    raise ValueError(f"{metadata_file} is not under the external volume base {warehouse_url}")


def table_sql(name: str, rel_path: str) -> str:
    return f"""
CREATE ICEBERG TABLE IF NOT EXISTS {name}
  EXTERNAL_VOLUME = 'NYC_TAXI_VOL'
  CATALOG = 'NYC_TAXI_OBJECT_STORE'
  METADATA_FILE_PATH = '{rel_path}';
ALTER ICEBERG TABLE {name} REFRESH '{rel_path}';
"""


def main() -> None:
    cfg = load_config()
    require(cfg.aws_account_id, "AWS_ACCOUNT_ID")
    spark = build_spark("export_snowflake_sql", cfg)

    out_dir = SNOWFLAKE_DIR / "generated"
    out_dir.mkdir(exist_ok=True)
    (out_dir / "01_setup.sql").write_text(render_setup(cfg.bucket, cfg.aws_account_id))

    parts = [
        "-- Generated by pipeline.snowflake.export_snowflake_sql. Re-generate after each pipeline run.\n",
        "USE ROLE ACCOUNTADMIN;\nUSE WAREHOUSE NYC_TAXI_WH;\nUSE SCHEMA NYC_TAXI.ANALYTICS;\n",
    ]
    for name in TABLES:
        fq = f"polaris.{cfg.namespace}.{name}"
        latest = spark.sql(
            f"SELECT file FROM {fq}.metadata_log_entries ORDER BY `timestamp` DESC LIMIT 1"
        ).first().file
        rel = relative_metadata_path(latest, cfg.warehouse_url)
        print(f"{name}: {rel}")
        parts.append(table_sql(name, rel))
    (out_dir / "02_tables.sql").write_text("".join(parts))
    print(f"Wrote {out_dir / '01_setup.sql'} and {out_dir / '02_tables.sql'}")
    spark.stop()


if __name__ == "__main__":
    main()
